void ensureOutputDirectory(const std::string& outputPath);
std::multimap<double, Alignment*> generateBadLandscapes(RandomVariable* rng, ThreadPool* threads, Alignment* originalAlignment, int numReplicates, int numTwists);
void printHeader(void);
std::string powerLabel(double x);
static void recomputeLikelihoods(TreeCache& cache, Alignment* alignment, ThreadPool* threads);



int main(int argc, char* argv[]) {

    printHeader();

    // instantiate random variable and thread pool objects
    RandomVariable rng;
    ThreadPool threads;

    // read the user settings
    UserSettings& settings = UserSettings::userSettings();
    settings.readSettings(argc, argv);
    rng.setSeed(settings.getSeed());                // the taxon subsample, twists and MCMC all draw from it
    settings.print();
    ensureOutputDirectory(settings.getOutputDirectoryName());
    bool analyticsOnly = false;
    int numTaxa = 10;
    int nReps = 50;

    // read the alignment file
    Alignment* originalAlignment = new Alignment(settings.getInputFileName());
    Alignment* data = originalAlignment;
    if (originalAlignment->getNumTaxa() > numTaxa)
        data = new Alignment(*originalAlignment, numTaxa, &rng);
    if (settings.getNumTwists() > 1)
        {
        std::multimap<double, Alignment*> twistedAlignments = generateBadLandscapes(&rng, &threads, data, 100, settings.getNumTwists());

        std::cout << "   * Selecting alignment with " << twistedAlignments.rbegin()->first << " peaks (TBR)" << std::endl;
        for (auto [key,val] : twistedAlignments)
            delete val;
        // data is still the taxon subsample (or the original alignment itself), never one of the twisted
        // alignments just deleted. Earlier versions pointed data at the selected twisted alignment and
        // then deleted it a second time here, which crashed every run whose input had more than numTaxa
        // taxa, after all of the alignment files had been written.
        if (data != originalAlignment)
            delete data;
        delete originalAlignment;
        std::cout << "   Completed generating twisted data matrices" << std::endl;
        return EXIT_SUCCESS;
        }
    BitSetFactory::getFactory().initialize(data->getNumTaxa());
    data->print(settings.getOutputFileName() + ".nex");
    data->summarize();
    data->compress();
        
    // Optionally integrate branch lengths out under an IID Exp() prior (Laplace) in addition to the ML
    // fit. Off unless -l yes is given: the finite-difference Hessian makes it the larger part of the
    // likelihood pass (about 64% of it at nine taxa).
    LikelihoodCalculator::setComputeMarginalLikelihood(settings.getComputeMarginalLikelihoods());
    LikelihoodCalculator::setExponentialPriorRate(10.0);
    LikelihoodCalculator::setMarginalHessianMethod(1);

    // Build the canonical tree set once, in the NNI cache, which owns the table of tree records. The
    // NNI2 and TBR caches share that table and keep only their own neighborhoods; earlier versions
    // copied every record, and its Tree object, into each of them.
    TreeCache treeCacheNni("NNI");
    TreeLikelihoods treeLikelihoods(&treeCacheNni);
    ExhaustiveSearch exhaustive(data, &treeCacheNni, &threads);
    double klDivergence = treeCacheNni.calculatePosteriorProbabilities();
    std::cout << "KL = " << klDivergence << std::endl;

    TreeCache treeCacheNni2("NNI2", &treeCacheNni);
    TreeCache treeCacheTbr("TBR", &treeCacheNni);

    // NNI2 is built from the NNI neighborhoods, so both are generated here, while the NNI neighbors
    // exist. TBR, whose neighborhoods are twenty times larger, is generated only when it is analyzed,
    // after the NNI and NNI2 neighborhoods have been released, so the three are never resident at once.
    // None is generated by building trees: NNI and TBR come from split masks (NniSplitNeighbors,
    // TbrSplitNeighbors) and NNI2 from the NNI rows, each in parallel.
    NniSplitNeighbors nniNeighbors(&treeCacheNni, data->getNumTaxa());
    nniNeighbors.generateAll(&threads);

    TreeNeighborGeneratorNNI2 treeNeighborGeneratorNni2(&treeCacheNni2, &treeCacheNni);
    treeNeighborGeneratorNni2.generateAll(&threads);

    TbrSplitNeighbors tbrNeighbors(&treeCacheTbr, data->getNumTaxa());

    // MAP tree. Its partitions are read from the Tree objects, so build it before freeing them, and
    // snapshot the MAP hash and each split's member-tree hashes into cache-independent structures so
    // the per-move analytics below do not depend on any particular cache (or its trees) staying alive.
    MapTree mapTree(&treeCacheNni);
    uint64_t mapHash = mapTree.getMapTree();
    std::vector<std::pair<std::string, std::vector<uint64_t>>> partitionHashLists;
    for (const auto& [part, trees] : mapTree.getPartitions())
        {
        std::vector<uint64_t> hashes;
        hashes.reserve(trees.size());
        for (TreeInfo* info : trees)
            hashes.push_back(info->hash);
        partitionHashLists.emplace_back(mapTree.partitionString(part), std::move(hashes));
        }

    // Bipartitions beyond the MAP tree's: every other split with posterior probability of at least
    // 0.10, which takes in every split of the majority-rule consensus and its main competitors. Their
    // efficiencies are written with the MAP tree's, and all of them are followed through the MCMC runs,
    // so that the estimate of the MAP tree's probability can be set against the estimates of the split
    // probabilities from which a consensus tree is built. At most 63 functionals are followed (the MAP
    // tree and 62 splits), the best supported first.
    const double minSplitProbability = 0.10;
    size_t numMapPartitions = partitionHashLists.size();
    std::vector<double> partitionProbability;
    for (const auto& [label, hashes] : partitionHashLists)
        {
        double p = 0.0;
        for (uint64_t h : hashes)
            p += treeCacheNni.getTreeInfo(h)->posteriorProbability;
        partitionProbability.push_back(p);
        }
    {
        std::unordered_map<uint16_t, double> splitProbability;
        for (auto& [hash, info] : treeCacheNni.getCache())
            for (uint16_t part : info->tree->getPartitions())
                splitProbability[part] += info->posteriorProbability;
        std::vector<std::pair<double, uint16_t>> extra;
        for (const auto& [part, p] : splitProbability)
            if (p >= minSplitProbability && mapTree.getPartitions().count(part) == 0)
                extra.emplace_back(p, part);
        std::sort(extra.begin(), extra.end(), [](const auto& a, const auto& b)
            {
            return (a.first != b.first) ? a.first > b.first : a.second < b.second;
            });
        if (extra.size() + numMapPartitions > 62)
            extra.resize(62 > numMapPartitions ? 62 - numMapPartitions : 0);
        std::unordered_map<uint16_t, size_t> slot;
        for (const auto& [p, part] : extra)
            {
            slot[part] = partitionHashLists.size();
            partitionHashLists.emplace_back(mapTree.partitionString(part), std::vector<uint64_t>());
            partitionProbability.push_back(p);
            }
        if (slot.empty() == false)
            for (auto& [hash, info] : treeCacheNni.getCache())
                for (uint16_t part : info->tree->getPartitions())
                    {
                    auto it = slot.find(part);
                    if (it != slot.end())
                        partitionHashLists[it->second].second.push_back(hash);
                    }
    }
    std::cout << "   Following the MAP tree and " << partitionHashLists.size() << " bipartitions (" << numMapPartitions
              << " in the MAP tree, " << partitionHashLists.size() - numMapPartitions << " others with probability >= "
              << minSplitProbability << ")" << std::endl;
    bool mapIsMajorityRule = true;
    for (size_t k = 0; k < numMapPartitions; k++)
        if (!(partitionProbability[k] > 0.5))
            mapIsMajorityRule = false;

    // The MCMC side of the comparison (Mcmc::writeFunctionalReport): functional 0 is the MAP tree, k >= 1
    // the k-th bipartition above. The asymptotic variances of the exactly analyzed kernels are filled in
    // as each move and power is analyzed, and read back for the plain MCMC runs on the same kernel.
    FunctionalReport functionalReport;
    functionalReport.labels.push_back("MAPtree");
    functionalReport.exact.push_back(treeCacheNni.getTreeInfo(mapHash)->posteriorProbability);
    functionalReport.membership[mapHash] |= 1;
    for (size_t k = 0; k < partitionHashLists.size(); k++)
        {
        functionalReport.labels.push_back(partitionHashLists[k].first);
        functionalReport.exact.push_back(partitionProbability[k]);
        for (uint64_t h : partitionHashLists[k].second)
            functionalReport.membership[h] |= (uint64_t(1) << (k + 1));
        }
    std::map<std::pair<std::string, double>, std::vector<double>> analyticVariance;   // (move, power) -> per functional
    // -c: the replicates start from trees drawn uniformly ("random"), from the exact posterior
    // ("posterior"), or, with "both", from uniform draws as usual, after which each plain MCMC run is
    // repeated from posterior draws (sampler "MCMC-stationary", convergence logs "..._stationary").
    const bool startPosterior = (settings.getChainStart() == "posterior");
    const bool startBoth      = (settings.getChainStart() == "both");
    auto setReport = [&](Mcmc& m, const std::string& sampler, const std::string& move, double power, bool analyzedKernel)
        {
        m.setStartFromPosterior(startPosterior || sampler == "MCMC-stationary");
        functionalReport.sampler = sampler;
        functionalReport.move    = move;
        functionalReport.power   = power;
        functionalReport.asymptoticVariance.assign(functionalReport.labels.size(), std::numeric_limits<double>::quiet_NaN());
        auto it = analyticVariance.find({ move, power });
        if (analyzedKernel && it != analyticVariance.end())
            functionalReport.asymptoticVariance = it->second;
        if (sampler == "Gibbs")                                   // independent draws: p (1 - p)
            for (size_t k = 0; k < functionalReport.exact.size(); k++)
                functionalReport.asymptoticVariance[k] = functionalReport.exact[k] * (1.0 - functionalReport.exact[k]);
        m.setFunctionalReport(&functionalReport);
        };

    // Release the heavyweight Tree objects now. The MAP-tree partitions were their last consumer: the
    // TBR neighbor generator rebuilds each tree from its compact encoding as it goes, and the kernel
    // analysis and the profile MCMC read only hashes, neighborhoods, and cached likelihoods. The table
    // is shared, so this releases them for every move set.
    treeCacheNni.freeTreeObjects();

    // Output files (shared across all moves and powers; rows are self-identifying via their columns).
    std::string basinTableFileName = settings.getOutputFileName() + ".basins.tsv";
    std::ofstream basinsOut(basinTableFileName);
    if (!basinsOut)
        throw std::runtime_error("Could not open basin table file: " + basinTableFileName);
    TreeSpace::writeBasinTableHeader(basinsOut);

    std::string diagnosticsFileName = settings.getOutputFileName() + ".markov.tsv";
    std::ofstream diagnosticsOut(diagnosticsFileName);
    if (!diagnosticsOut)
        throw std::runtime_error("Could not open Markov-chain diagnostics file: " + diagnosticsFileName);
    std::string efficiencyFileName = settings.getOutputFileName() + ".eff.tsv";
    std::ofstream effOut(efficiencyFileName);
    if (!effOut)
        throw std::runtime_error("Could not open Markov-chain efficiency file: " + efficiencyFileName);
    std::string stateReportFileName = settings.getOutputFileName() + ".state.tsv";
    std::ofstream stateOut(stateReportFileName);
    if (!stateOut)
        throw std::runtime_error("Could not open per-tree state-report file: " + stateReportFileName);
    MarkovChainAnalyzer::writeTsvHeader(diagnosticsOut);
    MarkovChainAnalyzer::writeEfficiencyTsvHeader(effOut);
    std::string functionalFileName = settings.getOutputFileName() + ".mcmc.functionals.tsv";
    std::ofstream functionalOut;
    if (analyticsOnly == false)
        {
        functionalOut.open(functionalFileName);
        if (!functionalOut)
            throw std::runtime_error("Could not open MCMC functional file: " + functionalFileName);
        FunctionalReport::writeHeader(functionalOut);
        functionalReport.out = &functionalOut;
        }
    LandscapeMixingCollator::writeStateReportHeader(stateOut);

    std::vector<double> powers = { 0.0, 0.02, 0.05, 0.1, 0.2, 0.3 };
    bool writeSmallStateFiles = (data->getNumTaxa() <= 8);

    // The exact analytics for one move set: landscape, basin table, and the per-power kernel diagnostics.
    auto analyzeMove = [&](TreeCache* c, const std::string& moveName, const std::string& fileTag) 
        {
        TreeSpace space(c, moveName);
        space.characterize();
        space.printPosterior();
        space.printPosterior(settings.getOutputFileName() + "." + fileTag + ".true");
        space.writeRuggednessStatistics(settings.getOutputFileName() + "." + fileTag + ".ruggedness.tsv");
        space.writeBasinTable(basinsOut, mapHash);
        basinsOut.flush();

        // The power loop needs only the per-tree landscape records, which do not depend on the power.
        // Build them now and release the landscape graph, so that it is not resident alongside each
        // power's transition kernel.
        space.landscapeByHash(mapHash);
        space.releaseGraph();

        for (double power : powers)
            {
            std::cout << "   Analyzing " << moveName << " with power " << power << "\n";

            c->sortNeighborsByLikelihood();
            c->cacheNeighborProposalProbabilities(power);

            MarkovChainAnalyzer analyzer(&threads, c, moveName + " (" + std::to_string(power) + ")", true);

            LandscapeMixingCollator::writeStateReport(stateOut, moveName, power, analyzer, space, mapHash);
            stateOut.flush();

            double chainLength = static_cast<double>(settings.getChainLength());
            // The relaxation time 1/(1 - SLEM). Where lambda_min is unresolved, 1/(1 - lambda_2), a lower
            // bound; where lambda_2 is unresolved as well, NaN ("NA"), which is itself a warning.
            SpectralInfo spec = analyzer.getSpectralInfo();
            double relaxationTime = spec.relaxation_time;
            if (!std::isfinite(relaxationTime) && std::isfinite(spec.lambda2_algebraic) && spec.lambda2_algebraic < 1.0)
                relaxationTime = 1.0 / (1.0 - spec.lambda2_algebraic);
            std::vector<double>& variances = analyticVariance[{ moveName, power }];
            EfficiencyInfo mapEff = analyzer.efficiencyFor(analyzer.indicatorForTree(mapHash));
            analyzer.writeEfficiencyTsvRow(effOut, moveName, power, "MAPtree", mapEff, 1, mapIsMajorityRule ? 1 : 0, chainLength,
                                           relaxationTime);
            variances.push_back(mapEff.asymptotic_variance);
            for (size_t k = 0; k < partitionHashLists.size(); k++)
                {
                EfficiencyInfo eff = analyzer.efficiencyFor(analyzer.indicatorForTrees(partitionHashLists[k].second));
                analyzer.writeEfficiencyTsvRow(effOut, moveName, power, partitionHashLists[k].first, eff,
                                               k < numMapPartitions ? 1 : 0, partitionProbability[k] > 0.5 ? 1 : 0, chainLength,
                                               relaxationTime);
                variances.push_back(eff.asymptotic_variance);
                }

            analyzer.writeTsvRow(diagnosticsOut, moveName, power);
            diagnosticsOut.flush();
            effOut.flush();

            if (writeSmallStateFiles)
                {
                std::string prefix = settings.getOutputFileName() + "." + moveName + ".beta_" + powerLabel(power);
                analyzer.writeSmallStateAnalysisFiles(prefix, false, true, false);
                }
            }
        };

    // Process each move set to completion -- analytics, then its MCMC runs -- and free its neighborhoods
    // before moving on, so beyond the shared tree records only one move's neighbor/kernel data is ever
    // live. The records themselves belong to the NNI cache and are released when it goes out of scope.

    // NNI (also carries the Metropolis-coupled and Gibbs runs, which sample the NNI cache)
    analyzeMove(&treeCacheNni, "NNI", "nni");
    if (analyticsOnly == false)
        {
        for (double power : powers)
            {
            std::string cfn = ".conv_NNI_" + std::to_string(power);
            Mcmc mcmc(&rng, &treeCacheNni, data, true, cfn, &threads);
            setReport(mcmc, "MCMC", "NNI", power, true);
            mcmc.run("MCMC (NNI, " + std::to_string(power) + ")", power, 0, nReps);
            if (startBoth)
                {
                Mcmc stationary(&rng, &treeCacheNni, data, true, cfn + "_stationary", &threads);
                setReport(stationary, "MCMC-stationary", "NNI", power, true);
                stationary.run("MCMC from the posterior (NNI, " + std::to_string(power) + ")", power, 0, nReps);
                }

            cfn = ".conv_mc3_NNI_" + std::to_string(power);
            Mcmc mcmcmc(&rng, &treeCacheNni, data, true, cfn, &threads);
            setReport(mcmcmc, "MCMCMC", "NNI", power, false);
            mcmcmc.run("MCMCMC (NNI, " + std::to_string(power) + ")", power, 0, nReps, 4);
            }
        Mcmc gibbs(&rng, &treeCacheNni, data, true, ".conv_Gibbs", &threads);
        setReport(gibbs, "Gibbs", "none", 0.0, false);
        gibbs.run("MCMC (Gibbs)", nReps);
        }
    treeCacheNni.freeNeighbors();

    // NNI2
    analyzeMove(&treeCacheNni2, "NNI2", "nni2");
    if (analyticsOnly == false)
        {
        for (double power : powers)
            {
            std::string cfn = ".conv_NNI2_" + std::to_string(power);
            Mcmc mcmc(&rng, &treeCacheNni2, data, true, cfn, &threads);
            setReport(mcmc, "MCMC", "NNI2", power, true);
            mcmc.run("MCMC (NNI2, " + std::to_string(power) + ")", power, 0, nReps);
            if (startBoth)
                {
                Mcmc stationary(&rng, &treeCacheNni2, data, true, cfn + "_stationary", &threads);
                setReport(stationary, "MCMC-stationary", "NNI2", power, true);
                stationary.run("MCMC from the posterior (NNI2, " + std::to_string(power) + ")", power, 0, nReps);
                }
            }
        }
    treeCacheNni2.freeNeighbors();

    // TBR (also carries the rTBR multiple-try runs, which sample the TBR cache)
    tbrNeighbors.generateAll(&threads);
    analyzeMove(&treeCacheTbr, "TBR", "tbr");
    if (analyticsOnly == false)
        {
        for (double power : powers)
            {
            std::string cfn = ".conv_TBR_" + std::to_string(power);
            Mcmc mcmc(&rng, &treeCacheTbr, data, true, cfn, &threads);
            setReport(mcmc, "MCMC", "TBR", power, true);
            mcmc.run("MCMC (TBR, " + std::to_string(power) + ")", power, 0, nReps);
            if (startBoth)
                {
                Mcmc stationary(&rng, &treeCacheTbr, data, true, cfn + "_stationary", &threads);
                setReport(stationary, "MCMC-stationary", "TBR", power, true);
                stationary.run("MCMC from the posterior (TBR, " + std::to_string(power) + ")", power, 0, nReps);
                }

            cfn = ".conv_rTBR_" + std::to_string(power);
            Mcmc rtbr(&rng, &treeCacheTbr, data, true, cfn, &threads);
            setReport(rtbr, "rTBR", "TBR", power, false);
            rtbr.run("MCMC (rTBR, " + std::to_string(power) + ")", power, 2 * (data->getNumTaxa() - 3), nReps);
            }
        }
    treeCacheTbr.freeNeighbors();

    basinsOut.close();
    std::cout << "   Basin barrier table written to " << basinTableFileName << "\n";
    std::cout << "   Markov-chain diagnostics written to " << diagnosticsFileName << "\n";
    if (analyticsOnly == false)
        std::cout << "   MCMC estimates of the MAP tree and bipartition probabilities written to " << functionalFileName << "\n";

    // clean up
    if (originalAlignment->getNumTaxa() > numTaxa)
        delete data;
    delete originalAlignment;

    return EXIT_SUCCESS;
}

void ensureOutputDirectory(const std::string& outputDir) {

    if (outputDir.empty())
        return;

    std::filesystem::path dir(outputDir);        // the whole path is the directory; nothing is stripped

    std::error_code ec;
    if (std::filesystem::exists(dir, ec))
        {
        if (!std::filesystem::is_directory(dir, ec))
            Msg::error("Output path exists but is not a directory: " + dir.string());
        return;
        }

    if (!std::filesystem::create_directories(dir, ec) || ec)
        Msg::error("Could not create output directory '" + dir.string() + "': " + ec.message());

    std::cout << "   Created output directory " << dir.string() << std::endl;
}

std::multimap<double, Alignment*> generateBadLandscapes(RandomVariable* rng, ThreadPool* threads, Alignment* originalAlignment, int numReplicates, int numTwists) {

    std::cout << "   Generating twisted landscapes" << std::endl;
    std::cout << "   * Number of twists: " << numTwists << std::endl;
    std::cout << "   * Number of landscapes: " << numReplicates << std::endl << std::endl;
    // re-enable the marginal later, on the few winners.
    LikelihoodCalculator::setComputeMarginalLikelihood(false);

    int numTaxa = originalAlignment->getNumTaxa();

    // fix the taxon set once, so every replicate shares the same enumerated trees and TBR neighbourhoods
    Alignment* base = new Alignment(*originalAlignment, numTaxa, rng);
    BitSetFactory::getFactory().initialize(base->getNumTaxa());

    // enumerate the trees and build the TBR neighbourhoods once
    TreeCache cache("TBR");
    TreeLikelihoods treeLikelihoods(&cache);
    ExhaustiveSearch exhaustive(base, &cache, threads);            // enumerates + an initial (discarded) pass
    TbrSplitNeighbors tbrNeighbors(&cache, base->getNumTaxa());
    tbrNeighbors.generateAll(threads);

    std::multimap<double, Alignment*> byBasins; // key: effectiveNumBasins (TBR)

    for (int i=0; i<numReplicates; i++)
        {
        Alignment* a = new Alignment(*base);
        a->twist(rng, numTwists);
        a->compress();

        recomputeLikelihoods(cache, a, threads);
        cache.calculatePosteriorProbabilities();

        TreeSpace space(&cache, "TBR");
        space.characterize();
        BasinSummary bs = space.basinSummary();

        byBasins.insert( {bs.effectiveNumBasins, a} );
        std::cout << "   [landscape screen] " << (i + 1) << "/" << numReplicates
                  << ": effectiveNumBasins=" << bs.effectiveNumBasins
                  << "  peaks(mass>0.05)=" << bs.numPeaksMassGreater05
                  << "  outsideMapBasin=" << bs.posteriorMassOutsideMapBasin << "\n";

        char temp[20];
        snprintf(temp, sizeof(temp), "%1.6lf", bs.effectiveNumBasins);
        std::string numPeaksStr(temp);
        std::string fileName = UserSettings::userSettings().getOutputFileName() + "_" + std::to_string(i+1) + "_" + numPeaksStr + ".nex";
        a->print(fileName);
        }

    delete base;
    cache.freeTreeCache();
    
    return byBasins;
}


